import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../../', import.meta.url));
const docs = path.join(root, 'docs');
const check = process.argv.includes('--check');
const read = (file) => readFile(path.join(root, file), 'utf8');
const json = (value) => JSON.stringify(value, null, 2) + '\n';
const generated = new Map();
const source = await read('packages/platform-api/openapi/platform-api.openapi.json');
const spec = JSON.parse(source);
const methods = new Set(['get', 'put', 'post', 'delete', 'patch', 'head', 'options', 'trace']);
const resourceOrder = ['Runs', 'Agents', 'Connections', 'Test Suites', 'Tests', 'Personas', 'Simulations', 'Traces', 'Recordings', 'Graders', 'Monitoring', 'Repository', 'Projects', 'Organization', 'Members', 'API keys'];
const stableRoutes = {
  createRun: 'create-a-run', getRun: 'get-a-run',
  listRunSimulations: 'list-simulations', cancelRun: 'cancel-a-run',
};
const ids = new Set();
const groups = new Map();

for (const [endpoint, item] of Object.entries(spec.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!methods.has(method)) continue;
    const id = operation.operationId;
    const resource = operation.tags?.[0];
    if (!/^[a-z][A-Za-z0-9]*$/.test(id ?? '') || ids.has(id) || !resource) throw new Error(`Missing, unsupported, or duplicate operation ID or resource tag: ${method} ${endpoint}`);
    ids.add(id);
    const slug = stableRoutes[id] ?? id.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
    const page = `api/${slug}`;
    if (generated.has(`${page}.mdx`)) throw new Error(`Duplicate API page: ${page}`);
    generated.set(`${page}.mdx`, `---\nopenapi: ${JSON.stringify(`openapi.json ${method.toUpperCase()} ${endpoint}`)}\n---\n`);
    if (!groups.has(resource)) groups.set(resource, []);
    groups.get(resource).push(page);
  }
}
if (ids.size === 0) throw new Error('The platform contract has no operations.');

// The contract stays byte-for-byte identical. Mintlify's deployment overlay
// supplies the hosted origin; it does not replace any endpoint definition.
generated.set('openapi.json', source);
const credentials = await read('apps/cli/src/platform/credentials.ts');
const defaults = [...credentials.matchAll(/^export const DEFAULT_PLATFORM_URL = "([^"]+)";$/gm)];
if (defaults.length !== 1 || JSON.stringify(spec.servers) !== '[{"url":"/"}]') {
  throw new Error('Platform server metadata changed. Review the docs deployment overlay.');
}
const origin = defaults[0][1];
const url = new URL(origin);
if (url.protocol !== 'https:' || url.origin !== origin) throw new Error('Expected a bare HTTPS hosted platform origin.');
generated.set('deployment-server.overlay.json', json({
  overlay: '1.0.0',
  info: { title: 'Egma hosted documentation deployment', version: '1.0.0' },
  extends: './openapi.json',
  actions: [{ target: '$.servers[0]', update: { url: origin } }],
}));

const config = JSON.parse(await read('docs/docs.json'));
const apiTabs = config.navigation.tabs.filter((tab) => tab.tab === 'API reference');
if (apiTabs.length !== 1) throw new Error('Expected one API reference tab.');
const resources = [...resourceOrder.filter((tag) => groups.has(tag)), ...[...groups.keys()].filter((tag) => !resourceOrder.includes(tag)).sort()];
const apiNavigation = {
  tab: 'API reference',
  pages: ['api/overview', ...resources.map((group) => ({ group, pages: groups.get(group) }))],
};
config.navigation.tabs[config.navigation.tabs.indexOf(apiTabs[0])] = apiNavigation;

// Read the same visual values as the application. Only the Mintlify selectors
// live in a docs-specific stylesheet; theme values stay in the product theme.
const theme = (await read('apps/web/ui/tailwind-theme.css'))
  .split('@custom-variant')[0]
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^@(?:import|source).*;\s*$/gm, '')
  .replace(/\[data-theme=["']dark["']\]/g, '.dark')
  .trim();
generated.set('style.css', '/* Generated by pnpm docs:generate. Edit the product theme or scripts/docs/style.css. */\n' + theme + '\n\n' + await read('scripts/docs/style.css'));
const primary = theme.match(/--color-ember-deep:\s*(#[\da-f]+);/i)?.[1];
const ember = theme.match(/--color-ember:\s*(#[\da-f]{6});/i)?.[1];
const paper = theme.match(/--color-paper:\s*(#[\da-f]{6});/i)?.[1];
const darkMix = theme.match(/--action:\s*color-mix\(in srgb, var\(--color-ember\) ([\d.]+)%, var\(--color-paper\)\)/)?.[1];
if (!primary || !ember || !paper || !darkMix) throw new Error('Expected the product Ember and dark-action theme tokens.');
// Mintlify accepts hex colors. Resolve the product's own dark-action mix.
const weight = Number(darkMix) / 100;
const paperChannels = paper.slice(1).match(/../g);
const light = '#' + ember.slice(1).match(/../g).map((channel, index) => Math.round(parseInt(channel, 16) * weight + parseInt(paperChannels[index], 16) * (1 - weight)).toString(16).padStart(2, '0')).join('');
config.colors = { primary, light, dark: primary };
generated.set('docs.json', json(config));
for (const mode of ['light', 'dark']) {
  generated.set(`logo/mark-${mode}.svg`, await read(`apps/web/public/brand/egma-mark-${mode}.svg`));
}

// The API folder contains one written overview and generated operation pages.
// Refuse to delete written pages: a rename should be an explicit docs edit.
const obsolete = [];
for (const name of await readdir(path.join(docs, 'api'))) {
  if (!name.endsWith('.mdx') || name === 'overview.mdx' || generated.has(`api/${name}`)) continue;
  const old = await read(`docs/api/${name}`);
  if (!/^---\nopenapi: [^\n]+\n---\n$/.test(old)) throw new Error(`Unexpected written API page: api/${name}`);
  obsolete.push(`api/${name}`);
}

const drift = [...obsolete];
for (const [file, content] of generated) {
  const destination = path.join(docs, file);
  if (check) {
    const current = await readFile(destination, 'utf8').catch((error) => {
      if (error.code !== 'ENOENT') throw error;
      return null;
    });
    if (current !== content) drift.push(file);
  } else {
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, content);
  }
}
if (check && drift.length) throw new Error(`Generated docs are stale: ${drift.join(', ')}. Run pnpm docs:generate.`);
if (!check) for (const file of obsolete) await unlink(path.join(docs, file));
console.log(`${check ? 'Checked' : 'Generated'} ${ids.size} API operations in ${groups.size} resources, the hosted overlay, and the shared docs theme.`);
